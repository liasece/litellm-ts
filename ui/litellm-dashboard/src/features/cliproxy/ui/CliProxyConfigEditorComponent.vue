<script setup lang="ts">
import { computed, reactive, ref } from "vue";
import UiButton from "../../platform/ui/UiButton.vue";
import UiIcon from "../../platform/ui/UiIcon.vue";
import UiCard from "../../platform/ui/UiCard.vue";
import UiAlert from "../../platform/ui/UiAlert.vue";
import { applyVisualValues, visualValuesFromConfig, type UserConfig } from "../logic/ConfigEditorLogic";
import { imageFields, quotaToggles, retentionFields, routingFields, routingToggles, runtimeToggles } from "../support/ConfigurationFields";
import CliProxySettingToggle from "./CliProxySettingToggleComponent.vue";
import CliProxyConfigField from "./CliProxyConfigFieldComponent.vue";
const props = defineProps<{ enabled: boolean; userConfig: UserConfig; saving: boolean }>();
const emit = defineEmits<{ save: [enabled: boolean, config: UserConfig]; openRaw: [] }>();
const sourceValues = computed(() => visualValuesFromConfig(props.userConfig));
const draftEnabled = ref(props.enabled);
const values = reactive({ ...sourceValues.value });
const dirty = computed(() => draftEnabled.value !== props.enabled || JSON.stringify(values) !== JSON.stringify(sourceValues.value));
const boundary = [
	["Listener", "127.0.0.1:8317"],
	["TLS", "Disabled on internal hop"],
	["Credentials", "Managed runtime directory"],
	["Remote management", "Loopback only"],
	["File logging", "Captured through process output"],
];
function reset() {
	draftEnabled.value = props.enabled;
	Object.assign(values, sourceValues.value);
}
</script>
<template>
	<div class="cp-stack cp-gap-16">
		<div class="cp-between cp-wrap cp-gap-12 cp-config-heading">
			<div>
				<h3>CLIProxy configuration</h3>
				<span class="cp-secondary"
					>Common settings are grouped by purpose. Unknown advanced fields are preserved when these settings are applied.</span
				>
			</div>
			<div class="cp-inline cp-gap-8">
				<UiButton @click="emit('openRaw')"
					><template #icon><UiIcon name="CodeOutlined" /></template>Edit raw config</UiButton
				><UiButton :disabled="!dirty || saving" @click="reset">Reset</UiButton
				><UiButton
					variant="primary"
					:loading="saving"
					:disabled="!dirty"
					@click="emit('save', draftEnabled, applyVisualValues(userConfig, values))"
					><template #icon><UiIcon name="SaveOutlined" /></template>Save and apply</UiButton
				>
			</div>
		</div>
		<UiAlert title="LiteLLM owns the private service boundary" class="cp-alert-with-description"
			>Host, port, TLS, credential directory, proxy API key, file logging and remote-management isolation are generated by LiteLLM and
			cannot be changed here. See the
			<a href="https://help.router-for.me/cn/configuration/options" target="_blank" rel="noreferrer"
				>official CLIProxyAPI configuration reference</a
			>.</UiAlert
		>
		<UiCard appearance="antd" class="cp-card cp-config-card" data-cliproxy-config-section="managed"
			><template #title
				><div class="cp-section-title">
					<div class="cp-inline cp-gap-8">
						<span class="cp-section-icon"><UiIcon name="SafetyCertificateOutlined" /></span
						><strong>Managed service boundary</strong>
					</div>
					<span class="cp-secondary cp-xs">Read-only security settings enforced whenever LiteLLM projects config.yaml.</span>
				</div></template
			>
			<div class="cp-boundary-grid">
				<div v-for="[label, value] in boundary" :key="label" class="cp-inset">
					<span class="cp-secondary cp-xs cp-block">{{ label }}</span
					><strong>{{ value }}</strong>
				</div>
			</div></UiCard
		>
		<UiCard appearance="antd" class="cp-card cp-config-card" data-cliproxy-config-section="runtime"
			><template #title
				><div class="cp-section-title">
					<div class="cp-inline cp-gap-8">
						<span class="cp-section-icon"><UiIcon name="DashboardOutlined" /></span><strong>Runtime and diagnostics</strong>
					</div>
					<span class="cp-secondary cp-xs"
						>Control the managed process and the amount of diagnostic work performed per request.</span
					>
				</div></template
			>
			<div class="cp-toggle-grid">
				<CliProxySettingToggle
					v-model="draftEnabled"
					title="Enable managed runtime"
					description="Starts CLIProxy with LiteLLM and keeps the private upstream available. Disabling it stops all models using this provider."
				/><CliProxySettingToggle
					v-for="toggle in runtimeToggles"
					:key="toggle.key"
					v-model="values[toggle.key]"
					:title="toggle.title"
					:description="toggle.description"
					:danger="toggle.danger"
					:class="{ 'cp-full': toggle.full }"
				/></div
		></UiCard>
		<UiCard appearance="antd" class="cp-card cp-config-card" data-cliproxy-config-section="routing"
			><template #title
				><div class="cp-section-title">
					<div class="cp-inline cp-gap-8">
						<span class="cp-section-icon"><UiIcon name="RetweetOutlined" /></span><strong>Routing and reliability</strong>
					</div>
					<span class="cp-secondary cp-xs">Choose credentials, retry recoverable failures and control session stickiness.</span>
				</div></template
			>
			<div class="cp-config-fields-grid">
				<CliProxyConfigField
					v-for="field in routingFields"
					:key="field.key"
					v-model="values[field.key]"
					:field="field"
					:class="{ 'cp-quarter': field.quarter }"
				/>
			</div>
			<div class="cp-toggle-grid">
				<CliProxySettingToggle
					v-for="toggle in routingToggles"
					:key="toggle.key"
					v-model="values[toggle.key]"
					:title="toggle.title"
					:description="toggle.description"
				/></div
		></UiCard>
		<UiCard appearance="antd" class="cp-card cp-config-card" data-cliproxy-config-section="quota"
			><template #title
				><div class="cp-section-title">
					<div class="cp-inline cp-gap-8">
						<span class="cp-section-icon"><UiIcon name="ApiOutlined" /></span
						><strong>Quota fallback and image generation</strong>
					</div>
					<span class="cp-secondary cp-xs"
						>Define how CLIProxy recovers from exhausted subscriptions and handles hosted image tools.</span
					>
				</div></template
			>
			<div class="cp-toggle-grid cp-toggle-grid--three">
				<CliProxySettingToggle
					v-for="toggle in quotaToggles"
					:key="toggle.key"
					v-model="values[toggle.key]"
					:title="toggle.title"
					:description="toggle.description"
				/>
			</div>
			<div class="cp-config-fields-grid cp-mt-16">
				<CliProxyConfigField v-for="field in imageFields" :key="field.key" v-model="values[field.key]" :field="field" /></div
		></UiCard>
		<UiCard appearance="antd" class="cp-card cp-config-card" data-cliproxy-config-section="logging"
			><template #title
				><div class="cp-section-title">
					<div class="cp-inline cp-gap-8">
						<span class="cp-section-icon"><UiIcon name="FileTextOutlined" /></span><strong>Log and usage retention</strong>
					</div>
					<span class="cp-secondary cp-xs">Bound diagnostic storage and the in-memory management usage queue.</span>
				</div></template
			>
			<div class="cp-retention-grid">
				<CliProxyConfigField v-for="field in retentionFields" :key="field.key" v-model="values[field.key]" :field="field" /></div
		></UiCard>
	</div>
</template>
